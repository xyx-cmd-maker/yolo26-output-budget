"""
yolo26-detection / tests/make_fixture_dataset.py
================================================
生成一个**极小合成数据集**，用于验证训练/评测/记录管线是否连通。

为什么不用 coco8（本机实测的教训）：
    coco8 需要从 github.com 下载，而本机 **github.com 完全不可达**。
    把"管线能不能跑通"依赖在一个断掉的网络上，等于没有冒烟测试。
    合成数据集 100% 本地、可复现、秒级生成。

★ 纪律（AGENTS.md §2）：
    本夹具产出的任何指标**没有任何科学含义**，只能用于 tier=debug/smoke。
    它生成的 yaml 故意**不放进** `src/configs/datasets/`，并写入
    `data/fixtures/`（已在 .gitignore 内），避免被人误当真实数据集。

用法：
    python tests/make_fixture_dataset.py                 # 默认 16/8/8 张，32x32 红方块
    python tests/make_fixture_dataset.py --n-train 32 --size 64
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]

CLASSES = ["red_square", "green_circle"]


def _draw(path: Path, size: int, cls: int, rng: random.Random) -> tuple[float, float, float, float]:
    """画一张图并返回归一化 YOLO 框 (cx, cy, w, h)。"""
    from PIL import Image, ImageDraw

    img = Image.new("RGB", (size, size), (30, 30, 30))
    d = ImageDraw.Draw(img)

    bw = rng.randint(size // 6, size // 3)
    bh = rng.randint(size // 6, size // 3)
    x0 = rng.randint(0, size - bw)
    y0 = rng.randint(0, size - bh)
    x1, y1 = x0 + bw, y0 + bh

    if cls == 0:
        d.rectangle([x0, y0, x1, y1], fill=(220, 40, 40))
    else:
        d.ellipse([x0, y0, x1, y1], fill=(40, 200, 80))

    # 加一点噪声，避免所有图完全一样（否则 E4 会报重复）
    for _ in range(size * 4):
        px, py = rng.randrange(size), rng.randrange(size)
        img.putpixel((px, py), (rng.randrange(256), rng.randrange(256), rng.randrange(256)))

    img.save(path, format="JPEG", quality=92)

    cx = (x0 + x1) / 2 / size
    cy = (y0 + y1) / 2 / size
    return cx, cy, bw / size, bh / size


def build(out_root: Path, n_train: int, n_val: int, n_test: int, size: int, seed: int) -> Path:
    rng = random.Random(seed)
    for split, n in (("train", n_train), ("val", n_val), ("test", n_test)):
        img_dir = out_root / "images" / split
        lbl_dir = out_root / "labels" / split
        img_dir.mkdir(parents=True, exist_ok=True)
        lbl_dir.mkdir(parents=True, exist_ok=True)
        for i in range(n):
            name = f"{split}_{i:04d}"
            img_path = img_dir / f"{name}.jpg"
            # 一张图 = 一个标签文件。不要在这里造出"多图共用一标签"的结构，
            # 那会让 data_card 的 E1 误报（每张图都必须有自己的 .txt）。
            box = _draw(img_path, size, i % len(CLASSES), rng)
            lines = [f"{i % len(CLASSES)} " + " ".join(f"{v:.6f}" for v in box)]
            # 30% 概率再叠一个第二类的框在同一张图上（测多类、多实例）
            if rng.random() < 0.3:
                bw = rng.randint(size // 8, size // 4)
                bh = rng.randint(size // 8, size // 4)
                x0 = rng.randint(0, size - bw)
                y0 = rng.randint(0, size - bh)
                from PIL import ImageDraw

                from PIL import Image

                with Image.open(img_path) as im:
                    d = ImageDraw.Draw(im)
                    d.rectangle([x0, y0, x0 + bw, y0 + bh], fill=(40, 200, 80))
                    im.save(img_path, format="JPEG", quality=92)
                lines.append(
                    f"{1 - i % len(CLASSES)} "
                    f"{(x0 + bw / 2) / size:.6f} {(y0 + bh / 2) / size:.6f} {bw / size:.6f} {bh / size:.6f}"
                )
            (lbl_dir / f"{name}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    yaml_path = out_root / "fixture.yaml"
    yaml_path.write_text(
        f"""# ⚠️ 合成夹具数据集 —— 只能用于 tier=debug/smoke，指标无科学含义
# 由 tests/make_fixture_dataset.py 生成，请勿手工编辑
name: synth_det_fixture
path: {out_root.as_posix()}
train: images/train
val: images/val
test: images/test

nc: {len(CLASSES)}
names:
  0: {CLASSES[0]}
  1: {CLASSES[1]}

license: SYNTHETIC_FIXTURE_NOT_A_REAL_DATASET
source_url: generated by tests/make_fixture_dataset.py
redistributable: true
notes: 合成数据，仅用于管线连通性验证。
""",
        encoding="utf-8",
    )
    meta = {
        "n_train": n_train,
        "n_val": n_val,
        "n_test": n_test,
        "image_size": size,
        "seed": seed,
        "classes": CLASSES,
        "warning": "合成夹具：指标无科学含义，禁止进入任何对外文本",
    }
    (out_root / "FIXTURE_META.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
    return yaml_path


def main() -> int:
    ap = argparse.ArgumentParser(description="生成合成夹具数据集")
    ap.add_argument("--out", type=Path, default=PROJECT_ROOT / "data" / "fixtures" / "synth_det")
    ap.add_argument("--n-train", type=int, default=24)
    ap.add_argument("--n-val", type=int, default=8)
    ap.add_argument("--n-test", type=int, default=8)
    ap.add_argument("--size", type=int, default=64)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()

    y = build(a.out, a.n_train, a.n_val, a.n_test, a.size, a.seed)
    print(f"夹具已生成：{y}")
    print(f"  图片：train={a.n_train} val={a.n_val} test={a.n_test}，尺寸 {a.size}x{a.size}")
    print("  ⚠️ 只能用于 tier=debug/smoke；指标无科学含义")
    print(f"\n下一步：\n  python -m src.utils.data_card --yaml {y}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
